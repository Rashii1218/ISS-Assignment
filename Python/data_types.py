# Integers
a = 10
b = -5
print(a, b)

# Strings and F-strings
name = "Rashi"
marks = 85
print(f"My name is {name} and I scored {marks} marks")

# Booleans
is_student = True
print(is_student)

# List
numbers = [1, 2, 3, 4]
print(numbers)

# Tuple
nums = (10, 20)
print(nums)

# Set
unique_numbers = {1, 2, 2, 3}
print(unique_numbers)

# Dictionary
student = {"name": "Rashi", "age": 20}
print(student)
